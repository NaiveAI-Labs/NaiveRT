"""Per-op descriptors -> generated entry shims, launch headers and pybind bindings.

An OpDescriptor states what a fused decode op is at the host boundary: its args
struct, its kernel variants (each a body with its own run()), its
launch geometry, and the parameters its Python binding takes and how they map
onto the args struct.  From that, `python -m naivert.kernels.opgen` writes:

* naivert/entry/<op>_launch.hpp   -- Variant enum + launch(args, variant, device, stream)
* naivert/entry/<op>_entry.cu     -- __global__ wrappers + configure-once + launch()
* <binding_dir>/gen_<op>_bindings.hpp / .cu -- the pybind entry points (nvcc-compiled)

`python -m naivert.kernels.opgen --check` verifies the generated files match the
descriptors (a host test runs it).
"""

from __future__ import annotations

import importlib
import pkgutil
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Mapping, Sequence

ROOT = Path(__file__).resolve().parents[2]
BANNER = "// GENERATED by `python -m naivert.kernels.opgen` from {source}. Do not edit by hand."

DTYPES = {  # descriptor dtype -> ATen scalar type
    "bf16": "at::kBFloat16",
    "f32": "at::kFloat",
    "fp8": "at::kFloat8_e4m3fn",
    "u8": "at::kByte",
    "i32": "at::kInt",
}


@dataclass(frozen=True)
class Variant:
    """One __global__ entry of the op."""

    name: str
    kernel: str
    body: str
    maxnreg: int | None = None
    launch_bounds: str | None = None  # e.g. "kBlockThreads, 1"
    prologue: str | None = None  # C++ statement(s) before the body call
    run_call: str | None = None  # default "<body>::run(args, shared)"
    shared_align: int = 16
    shared_bytes: str | None = None  # override of Launch.shared_bytes for this variant

    @property
    def enumerator(self) -> str:
        return "k" + "".join(part.capitalize() for part in self.name.split("_"))


@dataclass(frozen=True)
class Launch:
    grid: str  # C++ expression; may read `args.` fields
    block: str
    shared_bytes: str
    carveout: int = 100
    fixed_fields: Mapping[str, str] = field(default_factory=dict)
    guard: str | None = None  # C++ boolean over `args`; false -> the launch is skipped
    variant_selector: str | None = None  # host C++ expression over args/variant yielding a Variant


@dataclass(frozen=True)
class TensorParam:
    name: str
    dtype: str | None
    field: str
    ptr_type: str
    min_numel: str | None = None  # int64 expression over int params, constants, active_rows
    numel: str | None = None  # exact int64 expression
    min_nbytes: str | None = None
    rows_source: bool = False  # active_rows = numel / rows_divisor
    rows_divisor: str | None = None
    optional: bool = False  # a binding may omit it (Binding.omit) -> the field stays null
    dtype_expr: str | None = None  # build-dependent C++ ATen scalar type; use with dtype=None
    alignment: int | None = None  # required byte alignment of data_ptr(), including storage offset


@dataclass(frozen=True)
class IntParam:
    name: str
    field: str
    must_equal: int | str | None = None  # a literal, or a C++ constant expression (kernel traits)
    equals_device: bool = False
    low: int | None = None
    high: int | None = None


@dataclass(frozen=True)
class PointerListParam:
    name: str
    field: str
    count: int
    element: str


@dataclass(frozen=True)
class TensorListParam:
    """A Python list of `count` tensors filling a pointer-array field."""

    name: str
    field: str
    count: int
    element: str
    per_peer_device: bool = True  # tensor i must live on CUDA device i
    min_nbytes: str | None = None


Param = TensorParam | IntParam | PointerListParam | TensorListParam


@dataclass(frozen=True)
class Binding:
    name: str
    variants_by_rows: Mapping[int, str]
    omit: Sequence[str] = ()  # optional tensor params this binding does not take


@dataclass(frozen=True)
class OpDescriptor:
    name: str
    namespace: str
    args_struct: str
    args_include: str
    body_includes: Sequence[str]
    variants: Sequence[Variant]
    launch: Launch
    params: Sequence[Param]
    bindings: Sequence[Binding]
    source: str
    header_includes: Sequence[str] = ()  # extra includes in the launch header
    entry_includes: Sequence[str] = ()  # extra includes in the entry shim
    entry_usings: Sequence[str] = ()  # statements inside the op namespace (header + entry)
    constants: Mapping[str, str] = field(default_factory=dict)  # name -> int64 expression
    fills: Sequence[tuple[str, str]] = ()  # (args field, expression) after the params
    rows_field: str | None = None  # args field that receives active_rows
    kernel_namespace: str | None = None  # where the __global__ symbols live (default: namespace)
    binding_namespace: str = "naivert_naive_n0p5_model_ops"
    binding_dir: str = "naivert/kernels/model_ops/extension"
    entry_dir: str = "naivert/entry"

    def __post_init__(self) -> None:
        names = [variant.name for variant in self.variants]
        if len(set(names)) != len(names):
            raise ValueError(f"{self.name}: duplicate variant names")
        for variant in self.variants:
            if not variant.kernel.startswith("naivert_"):
                raise ValueError(f"{self.name}: kernel {variant.kernel!r} must start with naivert_")
        rows_sources = [p for p in self.params if isinstance(p, TensorParam) and p.rows_source]
        if len(rows_sources) != 1 or rows_sources[0].rows_divisor is None:
            raise ValueError(f"{self.name}: exactly one tensor parameter must define active_rows")
        for param in self.params:
            if isinstance(param, TensorParam) and param.alignment is not None:
                if param.alignment <= 0 or param.alignment & (param.alignment - 1):
                    raise ValueError(f"{self.name}: {param.name} alignment must be a positive power of two")
        optional = {p.name for p in self.params if isinstance(p, TensorParam) and p.optional}
        for binding in self.bindings:
            for variant_name in binding.variants_by_rows.values():
                if variant_name not in names:
                    raise ValueError(f"{self.name}: binding {binding.name} names unknown variant {variant_name!r}")
            if not set(binding.omit) <= optional:
                raise ValueError(f"{self.name}: binding {binding.name} omits non-optional params")

    @property
    def entry_path(self) -> str:
        return f"{self.entry_dir}/{self.name}_entry.cu"

    @property
    def launch_header_path(self) -> str:
        return f"{self.entry_dir}/{self.name}_launch.hpp"

    @property
    def bindings_cpp_path(self) -> str:
        # nvcc-compiled: args headers may carry device code (e.g. ProgressArgs)
        return f"{self.binding_dir}/gen_{self.name}_bindings.cu"

    @property
    def bindings_hpp_path(self) -> str:
        return f"{self.binding_dir}/gen_{self.name}_bindings.hpp"

    def variant(self, name: str) -> Variant:
        return next(v for v in self.variants if v.name == name)

    @property
    def rows_source(self) -> TensorParam:
        return next(p for p in self.params if isinstance(p, TensorParam) and p.rows_source)

    @property
    def tensor_params(self) -> list[TensorParam]:
        return [p for p in self.params if isinstance(p, TensorParam)]


# --------------------------------------------------------------------------- rendering


def _usings(op: OpDescriptor) -> str:
    return "".join(f"{line}\n" for line in op.entry_usings)


def render_launch_header(op: OpDescriptor) -> str:
    enumerators = ",\n".join(f"  {v.enumerator} = {i}" for i, v in enumerate(op.variants))
    extra = "".join(f'#include "{path}"\n' for path in op.header_includes)
    usings = _usings(op)
    usings = f"\n{usings}" if usings else ""
    return f"""#pragma once
{BANNER.format(source=op.source)}
#include "{op.args_include}"
{extra}#include <cuda_runtime_api.h>

namespace {op.namespace} {{
{usings}
enum class Variant {{
{enumerators}
}};

// Launch one variant of {op.name} on `device`/`stream`.
void launch(const {op.args_struct}& args, Variant variant, int device,
            cudaStream_t stream);

}}  // namespace {op.namespace}
"""


def _kernel_attrs(variant: Variant) -> str:
    attrs = ""
    if variant.launch_bounds is not None:
        attrs += f" __launch_bounds__({variant.launch_bounds})"
    if variant.maxnreg is not None:
        attrs += f" __maxnreg__({variant.maxnreg})"
    return attrs


def render_entry(op: OpDescriptor) -> str:
    includes = "\n".join(f'#include "{path}"' for path in (*op.body_includes, *op.entry_includes))
    separate = op.kernel_namespace is not None and op.kernel_namespace != op.namespace
    q = f"{op.namespace}::" if separate else ""  # qualify op types from the kernel namespace
    kq = f"{op.kernel_namespace}::" if separate else ""  # qualify kernels from the op namespace
    kernels = []
    for variant in op.variants:
        lines = []
        if variant.prologue:
            lines.append(f"  {variant.prologue}")
        lines.append(f"  extern __shared__ __align__({variant.shared_align}) unsigned char shared[];")
        lines.append(f"  {variant.run_call or f'{q}{variant.body}::run(args, shared)'};")
        kernels.append(
            f"__global__{_kernel_attrs(variant)} void {variant.kernel}(\n"
            f"    const __grid_constant__ {q}{op.args_struct} args) {{\n" + "\n".join(lines) + "\n}"
        )
    cases = []
    for index, variant in enumerate(op.variants):
        shared = variant.shared_bytes or op.launch.shared_bytes
        cases.append(
            f"    case Variant::{variant.enumerator}:\n"
            f"      configure_once({kq}{variant.kernel}, {index}, device, {shared});\n"
            f"      {kq}{variant.kernel}<<<{op.launch.grid}, {op.launch.block}, "
            f"{shared}, stream>>>(args);\n"
            f"      return;"
        )
    guard = ""
    if op.launch.guard:
        guard = (
            f"  if (!({op.launch.guard})) {{\n"
            "    return;  // preserved from the hand-written shim: unsupported shapes launch nothing\n"
            "  }\n"
        )
    fixed = "".join(f"  args.{name} = {value};\n" for name, value in op.launch.fixed_fields.items())
    selector = f"  variant = {op.launch.variant_selector};\n" if op.launch.variant_selector else ""
    usings = _usings(op)
    usings = f"{usings}\n" if usings else ""
    kernel_text = "\n".join(kernels)
    if separate:
        kernel_block = (
            f"namespace {op.kernel_namespace} {{\n\n"
            f"{kernel_text}\n\n}}  // namespace {op.kernel_namespace}\n\n"
            f"namespace {op.namespace} {{\n\n{usings}"
        )
    else:
        kernel_block = f"namespace {op.namespace} {{\n\n{usings}{kernel_text}\n\n"
    return f"""{BANNER.format(source=op.source)}
{includes}
#include "{op.launch_header_path}"
#include <cuda_runtime_api.h>
#include <cstring>

{kernel_block}namespace {{

template <class Kernel>
void configure_once(Kernel kernel, int variant, int device, int shared_bytes) {{
  static bool configured[{len(op.variants)}][64] = {{}};
  if (configured[variant][device]) {{
    return;
  }}
  cudaFuncSetAttribute(kernel, cudaFuncAttributeMaxDynamicSharedMemorySize,
                       shared_bytes);
  cudaFuncSetAttribute(kernel, cudaFuncAttributePreferredSharedMemoryCarveout,
                       {op.launch.carveout});
  configured[variant][device] = true;
}}

}}  // namespace

void launch(const {op.args_struct}& launch_args, Variant variant, int device,
            cudaStream_t stream) {{
  cudaSetDevice(device);
  // memcpy keeps the caller's zeroed padding; the captured parameters are
  // compared byte-for-byte with a host reconstruction.
  {op.args_struct} args;
  std::memcpy(&args, &launch_args, sizeof(args));
{guard}{fixed}{selector}  switch (variant) {{
{chr(10).join(cases)}
  }}
}}

}}  // namespace {op.namespace}
"""


def _signature(op: OpDescriptor, omit: Sequence[str] = (), internal: bool = False) -> str:
    parts = []
    for param in op.params:
        if isinstance(param, TensorParam):
            if param.optional and internal:
                parts.append(f"const at::Tensor* {param.name}")
            elif param.name not in omit:
                parts.append(f"at::Tensor {param.name}")
        elif isinstance(param, IntParam):
            parts.append(f"int64_t {param.name}")
        elif isinstance(param, TensorListParam):
            parts.append(f"const std::vector<at::Tensor>& {param.name}")
        else:
            parts.append(f"const std::vector<std::uint64_t>& {param.name}")
    return ", ".join(parts)


def _call_args(op: OpDescriptor, omit: Sequence[str] = ()) -> str:
    parts = []
    for param in op.params:
        if isinstance(param, TensorParam) and param.optional:
            parts.append("nullptr" if param.name in omit else f"&{param.name}")
        else:
            parts.append(param.name)
    return ", ".join(parts)


def render_bindings_header(op: OpDescriptor) -> str:
    decls = "\n".join(f"void {binding.name}({_signature(op, binding.omit)});" for binding in op.bindings)
    return f"""#pragma once
{BANNER.format(source=op.source)}
#include <ATen/ATen.h>
#include <cstdint>
#include <vector>

namespace {op.binding_namespace} {{

{decls}

}}  // namespace {op.binding_namespace}
"""


def render_bindings_cpp(op: OpDescriptor) -> str:
    rows = op.rows_source
    first_tensor = op.tensor_params[0].name
    if op.tensor_params[0].optional:
        raise ValueError(f"{op.name}: the first tensor parameter must not be optional")

    def ref(param: TensorParam) -> str:
        return f"(*{param.name})" if param.optional else param.name

    def guarded(param: TensorParam, lines: list[str]) -> list[str]:
        if not param.optional or not lines:
            return lines
        return [f"  if ({param.name} != nullptr) {{", *[f"  {line}" for line in lines], "  }"]

    checks: list[str] = []
    for name, value in op.constants.items():
        checks.append(f"  constexpr int64_t {name} = {value};")
    for param in op.params:
        if isinstance(param, TensorParam):
            lines = [f'  require_cuda_contiguous({ref(param)}, "{param.name}");']
            if param.dtype is not None:
                lines.append(
                    f'  TORCH_CHECK({ref(param)}.scalar_type() == {DTYPES[param.dtype]},\n'
                    f'              "{param.name} must be {param.dtype}");'
                )
            if param.dtype_expr is not None:
                lines.append(
                    f'  TORCH_CHECK({ref(param)}.scalar_type() == ({param.dtype_expr}),\n'
                    f'              "{param.name} has the wrong dtype for this build");'
                )
            if param.alignment is not None:
                lines.append(
                    f"  TORCH_CHECK(reinterpret_cast<std::uintptr_t>({ref(param)}.data_ptr()) % {param.alignment} == 0,\n"
                    f'              "{param.name} must be aligned to {param.alignment} bytes");'
                )
            if param.min_nbytes:
                lines.append(
                    f"  TORCH_CHECK({ref(param)}.nbytes() >= ({param.min_nbytes}),\n"
                    f'              "{param.name} is too small for {op.name}");'
                )
            checks.extend(guarded(param, lines))
        elif isinstance(param, IntParam):
            if isinstance(param.must_equal, str):
                checks.append(
                    f"  TORCH_CHECK({param.name} == ({param.must_equal}),\n"
                    f'              "{op.name} requires {param.name}=", ({param.must_equal}));'
                )
            elif param.must_equal is not None:
                checks.append(
                    f'  TORCH_CHECK({param.name} == {param.must_equal},\n'
                    f'              "{op.name} requires {param.name}={param.must_equal}");'
                )
            bounds = [
                f"{param.name} >= {param.low}" if param.low is not None else "",
                f"{param.name} <= {param.high}" if param.high is not None else "",
            ]
            bounds = [b for b in bounds if b]
            if bounds:
                checks.append(f'  TORCH_CHECK({" && ".join(bounds)}, "{op.name} {param.name} is out of range");')
        elif isinstance(param, TensorListParam):
            checks.append(
                f"  TORCH_CHECK({param.name}.size() == {param.count},\n"
                f'              "{op.name} {param.name} requires exactly {param.count} tensors");'
            )
    checks.append(
        f"  TORCH_CHECK({rows.name}.numel() >= {rows.rows_divisor} &&\n"
        f"                  {rows.name}.numel() % {rows.rows_divisor} == 0,\n"
        f'              "{rows.name} must contain whole active rows");'
    )
    checks.append(f"  const int64_t active_rows = {rows.name}.numel() / {rows.rows_divisor};")
    for param in op.tensor_params:
        lines = []
        if param.numel:
            lines.append(
                f"  TORCH_CHECK({ref(param)}.numel() == ({param.numel}),\n"
                f'              "{param.name} has the wrong size for {op.name}");'
            )
        if param.min_numel:
            lines.append(
                f"  TORCH_CHECK({ref(param)}.numel() >= ({param.min_numel}),\n"
                f'              "{param.name} is too small for {op.name}");'
            )
        checks.extend(guarded(param, lines))
    checks.append(f"  const int device = static_cast<int>({first_tensor}.get_device());")
    for param in op.tensor_params[1:]:
        checks.extend(guarded(param, [
            f"  TORCH_CHECK({ref(param)}.get_device() == device,\n"
            f'              "{op.name} tensors must share one device");'
        ]))
    for param in op.params:
        if isinstance(param, IntParam) and param.equals_device:
            checks.append(
                f"  TORCH_CHECK({param.name} >= 0 && {param.name} < 8 && {param.name} == device,\n"
                f'              "{op.name} {param.name} must match its CUDA device");'
            )
        elif isinstance(param, TensorListParam):
            device_rule = "static_cast<int>(i)" if param.per_peer_device else "device"
            size_check = (
                f"    TORCH_CHECK({param.name}[i].nbytes() >= ({param.min_nbytes}),\n"
                f'                "{op.name} {param.name} tensor is too small");\n'
                if param.min_nbytes else ""
            )
            checks.append(
                f"  for (std::size_t i = 0; i < {param.count}; ++i) {{\n"
                f'    require_cuda_contiguous({param.name}[i], "{param.name}");\n'
                f"    TORCH_CHECK({param.name}[i].get_device() == {device_rule},\n"
                f'                "{op.name} {param.name} tensor is on the wrong device");\n'
                f"{size_check}"
                f"  }}"
            )
    # The caller zeroes `args` with memset and passes it by reference: the captured
    # kernel parameters are compared byte-for-byte with a host reconstruction, so the
    # struct's padding must stay zero, and a by-value copy may not preserve padding.
    fills: list[str] = []
    for param in op.params:
        if isinstance(param, TensorParam):
            if param.optional:
                fills.append(
                    f"  args.{param.field} = {param.name} == nullptr ? nullptr\n"
                    f"      : reinterpret_cast<{param.ptr_type}>({param.name}->data_ptr());"
                )
            else:
                fills.append(f"  args.{param.field} = reinterpret_cast<{param.ptr_type}>({param.name}.data_ptr());")
        elif isinstance(param, IntParam):
            fills.append(f"  args.{param.field} = static_cast<decltype(args.{param.field})>({param.name});")
        elif isinstance(param, TensorListParam):
            fills.append(
                f"  for (std::size_t i = 0; i < {param.count}; ++i) {{\n"
                f"    args.{param.field}[i] = reinterpret_cast<{param.element}>({param.name}[i].data_ptr());\n"
                f"  }}"
            )
        else:
            fills.append(
                f"  TORCH_CHECK({param.name}.size() == {param.count},\n"
                f'              "{op.name} {param.name} requires exactly {param.count} pointers");\n'
                f"  for (std::size_t i = 0; i < {param.count}; ++i) {{\n"
                f'    TORCH_CHECK({param.name}[i] != 0, "{op.name} {param.name} must be non-zero");\n'
                f"    for (std::size_t j = 0; j < i; ++j) {{\n"
                f'      TORCH_CHECK({param.name}[i] != {param.name}[j], "{op.name} {param.name} must be unique");\n'
                f"    }}\n"
                f"    args.{param.field}[i] = reinterpret_cast<{param.element}>(\n"
                f"        static_cast<std::uintptr_t>({param.name}[i]));\n"
                f"  }}"
            )
    for field_name, expression in op.fills:
        fills.append(f"  args.{field_name} = static_cast<decltype(args.{field_name})>({expression});")
    if op.rows_field:
        fills.append(f"  args.{op.rows_field} = static_cast<decltype(args.{op.rows_field})>(active_rows);")
    bindings = []
    for binding in op.bindings:
        cases = "\n".join(
            f"    case {rows_count}:\n      variant = op::Variant::{op.variant(name).enumerator};\n      break;"
            for rows_count, name in sorted(binding.variants_by_rows.items())
        )
        allowed = ", ".join(str(r) for r in sorted(binding.variants_by_rows))
        bindings.append(
            f"void {binding.name}({_signature(op, binding.omit)}) {{\n"
            f"  int64_t active_rows = 0;\n"
            f"  int device = -1;\n"
            f"  op::{op.args_struct} args;\n"
            f"  std::memset(&args, 0, sizeof(args));\n"
            f"  checked_args({_call_args(op, binding.omit)}, args, active_rows, device);\n"
            f"  op::Variant variant = op::Variant::{op.variants[0].enumerator};\n"
            f"  switch (active_rows) {{\n{cases}\n"
            f"    default:\n"
            f'      TORCH_CHECK(false, "{binding.name} supports active rows {allowed}");\n'
            f"  }}\n"
            f"  c10::cuda::CUDAGuard guard({first_tensor}.device());\n"
            f"  op::launch(args, variant, device, at::cuda::getCurrentCUDAStream(device).stream());\n"
            f"  C10_CUDA_KERNEL_LAUNCH_CHECK();\n"
            f"}}"
        )
    return f"""{BANNER.format(source=op.source)}
#include <ATen/ATen.h>
#include <ATen/cuda/CUDAContext.h>
#include <c10/cuda/CUDAException.h>
#include <c10/cuda/CUDAGuard.h>
#include <torch/extension.h>
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <vector>
#include "naivert/common/torch_extension_utils.hpp"
#include "{op.launch_header_path}"
#include "{op.bindings_hpp_path}"

namespace {op.binding_namespace} {{

namespace {{

namespace op = {op.namespace};
using naivert_torch_extension::require_cuda_contiguous;

// Validate the binding parameters and fill the (zeroed) args struct in place;
// active_rows and device are returned for the variant selection and the launch.
void checked_args({_signature(op, internal=True)}, op::{op.args_struct}& args, int64_t& active_rows_out, int& device_out) {{
{chr(10).join(checks)}
{chr(10).join(fills)}
  active_rows_out = active_rows;
  device_out = device;
}}

}}  // namespace

{chr(10).join(bindings)}

}}  // namespace {op.binding_namespace}
"""


def render_all(op: OpDescriptor) -> dict[str, str]:
    return {
        op.launch_header_path: render_launch_header(op),
        op.entry_path: render_entry(op),
        op.bindings_hpp_path: render_bindings_header(op),
        op.bindings_cpp_path: render_bindings_cpp(op),
    }


# --------------------------------------------------------------------------- driver


def descriptors() -> list[OpDescriptor]:
    from naivert.kernels import ops as package

    found = []
    for info in sorted(pkgutil.iter_modules(package.__path__), key=lambda m: m.name):
        module = importlib.import_module(f"{package.__name__}.{info.name}")
        op = getattr(module, "OP", None)
        if isinstance(op, OpDescriptor):
            found.append(op)
    return found


def generated_files(root: Path = ROOT) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for op in descriptors():
        for relative, text in render_all(op).items():
            files[root / relative] = text
    return files


def check(root: Path = ROOT) -> list[str]:
    """Return the generated files that differ from (or are missing on) disk."""
    drifted = []
    for path, text in generated_files(root).items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            drifted.append(path.relative_to(root).as_posix())
    return drifted


def write(root: Path = ROOT) -> list[str]:
    written = []
    for path, text in generated_files(root).items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            written.append(path.relative_to(root).as_posix())
    return written


def main(argv: Sequence[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if "--check" in args:
        drifted = check()
        for path in drifted:
            print(f"drift: {path}")
        print(f"{len(drifted)} generated file(s) out of date")
        return 1 if drifted else 0
    for path in write():
        print(f"wrote {path}")
    return 0


