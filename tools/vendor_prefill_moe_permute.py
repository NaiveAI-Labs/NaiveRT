#!/usr/bin/env python3
"""Extract unchanged SGLang MoE layout kernels without its serving stack.

Use --source /path/to/sglang/python/sglang/srt/layers/moe/ep_moe/kernels.py.
The whole source hash is pinned; --check verifies the checked-in extraction.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'naivert/kernels/naive_n0p5/prefill_sglang'
REVISION = 'c68895d58bfb7edc6b50f5b4a8050571a200a768'
SOURCE = 'python/sglang/srt/layers/moe/ep_moe/kernels.py'
SOURCE_SHA = '5ddf6695a26017811c5b2b5024bb2948e71c0099189296dfd57db65ec0e9499e'
FUNCTIONS = {'permute.py': ('deepep_permute_triton_kernel',),
             'combine.py': ('_get_launch_config_2d', 'post_reorder_triton_kernel_for_cutlass_moe',
                            'post_reorder_for_cutlass_moe'),
             'scatter.py': ('_fwd_kernel_ep_scatter_1', '_fwd_kernel_ep_scatter_2')}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--source', type=Path, required=True)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    source = args.source.read_bytes()
    assert hashlib.sha256(source).hexdigest() == SOURCE_SHA, 'upstream source differs from pin'
    text = source.decode()
    nodes = {n.name: n for n in ast.parse(text).body if isinstance(n, ast.FunctionDef)}
    lines = text.splitlines(keepends=True)
    header = (f'# SPDX-License-Identifier: Apache-2.0\n'
              f'# Generated by tools/vendor_prefill_moe_permute.py; do not edit.\n'
              f'# SGLang {REVISION}, {SOURCE}.\n'
              f'# Kernel body is unchanged. See manifest.json and LICENSE.\n'
              'import triton\nimport triton.language as tl\n\n\n')
    outputs, extractions = {}, {}
    for filename, functions in FUNCTIONS.items():
        bodies, locations = [], {}
        for name in functions:
            node = nodes[name]
            start = min(n.lineno for n in [node, *node.decorator_list])
            bodies.append(''.join(lines[start - 1:node.end_lineno]).rstrip())
            locations[name] = [start, node.end_lineno]
        prefix = header if filename == 'permute.py' else header.replace('import triton\n', 'import torch\nimport triton\n')
        outputs[filename] = (prefix + '\n\n\n'.join(bodies) + '\n').encode()
        extractions[filename] = locations
    license_data = (ROOT / 'naivert/kernels/naive_n0p5/prefill_ext/fa4_cute/SGLANG_LICENSE').read_bytes()
    manifest = dict(repository='https://github.com/sgl-project/sglang', revision=REVISION,
                    source=SOURCE, source_sha256=SOURCE_SHA, extractions=extractions,
                    mode='verbatim function extraction; standalone Torch/Triton imports',
                    substitutions=[], license='Apache-2.0 (LICENSE)',
                    files={name: hashlib.sha256(data).hexdigest() for name, data in outputs.items()})
    outputs['LICENSE'] = license_data
    manifest['files']['LICENSE'] = hashlib.sha256(license_data).hexdigest()
    outputs['manifest.json'] = (json.dumps(manifest, indent=2) + '\n').encode()
    for name, content in outputs.items():
        dest = OUT / name
        if args.check:
            assert dest.read_bytes() == content, f'{dest} differs'
        else:
            dest.write_bytes(content)


if __name__ == '__main__':
    main()
