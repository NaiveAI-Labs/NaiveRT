class VendorError(RuntimeError):
    pass


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def banned_references(text: str, filename: str) -> list[str]:
    """Imports of, or dotted module strings naming, a banned package anywhere in ``text``."""
    found = []
    for node in ast.walk(ast.parse(text, filename)):
        if isinstance(node, ast.Import):
            found += [
                f"{filename}:{node.lineno}: import {alias.name}"
                for alias in node.names if alias.name.split(".")[0] in BANNED_ROOTS
            ]
        elif isinstance(node, ast.ImportFrom):
            if node.level == 0 and node.module and node.module.split(".")[0] in BANNED_ROOTS:
                found.append(f"{filename}:{node.lineno}: from {node.module} import ...")
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            if _BANNED_MODULE_STRING.fullmatch(node.value):
                found.append(f"{filename}:{node.lineno}: string {node.value!r}")
    return found


def _restore_upstream(raw: bytes, entry: Entry) -> bytes:
    return _substitute(raw.decode(), entry, (ORACLE_PATCH_REVERSAL,)).encode()


def _substitute(text: str, entry: Entry, substitutions: tuple[Substitution, ...] | None = None) -> str:
    for substitution in entry.substitutions if substitutions is None else substitutions:
        found = text.count(substitution.old)
        if found != substitution.count:
            raise VendorError(
                f"{entry.out}: expected {substitution.count} occurrence(s) of "
                f"{substitution.old!r}, found {found}"
            )
        text = text.replace(substitution.old, substitution.new)
    return text


# --------------------------------------------------------------------------- extraction


@dataclass
class _Statement:
    node: ast.stmt
    kind: str
    bound: set[str]
    refs: set[str]
    aliases: tuple[ast.alias, ...] = ()


def _referenced_names(node: ast.AST) -> set[str]:
    names = set()
    for child in ast.walk(node):
        if isinstance(child, ast.Name):
            names.add(child.id)
        elif isinstance(child, (ast.Global, ast.Nonlocal)):
            names.update(child.names)
    return names


def _alias_binding(node: ast.Import | ast.ImportFrom, alias: ast.alias) -> str:
    if alias.asname:
        return alias.asname
    return alias.name.split(".")[0] if isinstance(node, ast.Import) else alias.name


def _is_main_guard(node: ast.stmt) -> bool:
    return isinstance(node, ast.If) and ast.unparse(node.test) in (
        "__name__ == '__main__'", '__name__ == "__main__"',
    )


def _statements(tree: ast.Module, filename: str) -> tuple[list[_Statement], list[str]]:
    statements, dropped = [], []
    body = tree.body
    if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
            and isinstance(body[0].value.value, str):
        statements.append(_Statement(body[0], "docstring", set(), set()))
        body = body[1:]
    for node in body:
        if isinstance(node, ast.ImportFrom) and node.module == "__future__":
            statements.append(_Statement(node, "future", set(), set()))
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            if any(alias.name == "*" for alias in node.names):
                raise VendorError(f"{filename}:{node.lineno}: star import cannot be extracted")
            for alias in node.names:
                statements.append(_Statement(
                    node, "import", {_alias_binding(node, alias)}, set(), (alias,),
                ))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            kind = "class" if isinstance(node, ast.ClassDef) else "function"
            statements.append(_Statement(node, kind, {node.name}, _referenced_names(node)))
        elif isinstance(node, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            bound = {
                child.id for target in targets for child in ast.walk(target)
                if isinstance(child, ast.Name) and isinstance(child.ctx, ast.Store)
            }
            statements.append(_Statement(
                node, "assignment" if bound else "statement", bound, _referenced_names(node),
            ))
        elif isinstance(node, ast.Expr):
            statements.append(_Statement(node, "statement", set(), _referenced_names(node)))
        elif _is_main_guard(node):
            dropped.append(f"lines {node.lineno}-{node.end_lineno}: if __name__ == '__main__' block")
        else:
            raise VendorError(
                f"{filename}:{node.lineno}: top-level {type(node).__name__} cannot be extracted"
            )
    return statements, dropped


def _relative_import(module: str, out_module: list[str]) -> tuple[str | None, int]:
    """``naive_ops_lib.a.b`` seen from naive_ops module ``out_module`` as (module, level)."""
    target = module.split(".")[1:]
    package = out_module[:-1]
    common = 0
    while common < min(len(target), len(package)) and target[common] == package[common]:
        common += 1
    return ".".join(target[common:]) or None, len(package) - common + 1


def extract(text: str, entry: Entry, source_sha: str, *, upstream: bool = False) -> tuple[str, dict]:
    tree = ast.parse(text, entry.source)
    statements, dropped = _statements(tree, entry.source)
    lines = text.splitlines(keepends=True)
    top_bound = set().union(*(statement.bound for statement in statements))
    missing = [root for root in entry.roots if root not in top_bound]
    if missing:
        raise VendorError(f"{entry.source}: roots not defined at top level: {missing}")

    needed = set(entry.roots)
    kept: set[int] = set()
    changed = True
    while changed:
        changed = False
        for index, statement in enumerate(statements):
            if index in kept or statement.kind in ("docstring", "future"):
                continue
            wanted = statement.bound & needed if statement.bound else \
                statement.refs & needed & top_bound
            if wanted:
                kept.add(index)
                needed |= statement.refs
                changed = True

    first_line = min(
        [s.node.lineno for s in statements]
        + [d.lineno for s in statements for d in getattr(s.node, "decorator_list", [])]
    )
    leading = "".join(
        line for line in lines[:first_line - 1] if line.lstrip().startswith("#")
    )
    out_module = entry.out[len(OPS_OUT) + 1:-len(".py")].split("/")
    source = (
        f"{entry.source} with the oracle's patch reverted (upstream sha256 {source_sha})"
        if upstream else f"{entry.source} (sha256 {source_sha})"
    )
    header = (
        "# Generated by tools/vendor_prefill_ext.py; do not edit.\n"
        f"# Source: {source}, reduced to the top-level\n"
        f"# definitions reachable from: {', '.join(entry.roots)}.\n"
        "# prefill_ext/manifest.json lists the kept definitions and the substitutions.\n"
    )
    parts = [header + leading]
    for statement in statements:
        if statement.kind in ("docstring", "future"):
            parts.append(ast.get_source_segment(text, statement.node) + "\n")

    # Imports: keep the aliases kept code binds, in source order, one statement per source
    # statement; naive_ops_lib imports become relative to the copied package.
    import_nodes: dict[int, list[ast.alias]] = {}
    order: list[ast.stmt] = []
    for index, statement in enumerate(statements):
        if statement.kind != "import":
            continue
        if id(statement.node) not in import_nodes:
            import_nodes[id(statement.node)] = []
            order.append(statement.node)
        if index in kept:
            import_nodes[id(statement.node)] += list(statement.aliases)
    import_lines, dropped_imports = [], []
    for node in order:
        aliases = import_nodes[id(node)]
        removed = [alias.name for alias in node.names if alias not in aliases]
        if removed:
            dropped_imports.append(f"line {node.lineno}: {', '.join(removed)}")
        if not aliases:
            continue
        if isinstance(node, ast.Import):
            if any(alias.name.split(".")[0] == OPS_ROOT for alias in aliases):
                raise VendorError(f"{entry.source}:{node.lineno}: absolute naive_ops_lib import")
            import_lines.append(ast.unparse(ast.Import(names=aliases)))
            continue
        module, level = node.module, node.level
        if level == 0 and module and module.split(".")[0] == OPS_ROOT:
            module, level = _relative_import(module, out_module)
        import_lines.append(ast.unparse(ast.ImportFrom(module=module, names=aliases, level=level)))
    if import_lines:
        parts.append("\n".join(import_lines) + "\n")

    kept_records = []
    for index in sorted(kept):
        statement = statements[index]
        if statement.kind == "import":
            continue
        node = statement.node
        start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
        while start > 1 and lines[start - 2].startswith("#"):
            start -= 1
        parts.append("\n" + "".join(lines[start - 1:node.end_lineno]))
        kept_records.append({
            "name": ", ".join(sorted(statement.bound)) or ast.unparse(node).split("\n")[0],
            "kind": statement.kind,
            "source_lines": [start, node.end_lineno],
        })
    for index, statement in enumerate(statements):
        if index not in kept and statement.kind not in ("docstring", "future", "import"):
            label = ", ".join(sorted(statement.bound)) or ast.unparse(statement.node).split("\n")[0]
            dropped.append(f"lines {statement.node.lineno}-{statement.node.end_lineno}: {label}")

    body = "\n".join(part.rstrip("\n") + "\n" for part in parts)
    return body, {"kept": kept_records, "dropped": dropped, "dropped_imports": dropped_imports}


# --------------------------------------------------------------------------- FA4 closure


def fa4_closure(root: Path) -> list[str]:
    """Module files ``cute/__init__.py`` reaches through (possibly nested) imports."""
    seen, pending = set(), ["__init__.py"]
    while pending:
        name = pending.pop()
        if name in seen:
            continue
        seen.add(name)
        tree = ast.parse((root / name).read_text(), name)
        for node in ast.walk(tree):
            modules = []
            if isinstance(node, ast.Import):
                modules = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                if node.level == 1:
                    base = node.module or ""
                    modules = [base] if base else []
                    modules += [f"{base}.{alias.name}".lstrip(".") for alias in node.names]
                    modules = [f"{FA4_OLD_PACKAGE}.{module}" for module in modules]
                elif node.level == 0 and node.module:
                    modules = [node.module]
                    modules += [f"{node.module}.{alias.name}" for alias in node.names]
            for module in modules:
                if not module.startswith(FA4_OLD_PACKAGE + "."):
                    continue
                leaf = module[len(FA4_OLD_PACKAGE) + 1:].split(".")[0]
                if (root / f"{leaf}.py").is_file():
                    pending.append(f"{leaf}.py")
    return sorted(seen)


def third_party_roots(files: dict[str, bytes]) -> dict[str, list[str]]:
    """Top-level non-stdlib import roots of each generated module, for the manifest."""
    stdlib = set(sys.stdlib_module_names) | set(dir(builtins))
    roots: dict[str, set[str]] = {}
    for path, data in files.items():
        if not path.endswith(".py"):
            continue
        for node in ast.walk(ast.parse(data.decode(), path)):
            names = []
            if isinstance(node, ast.Import):
                names = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                names = [node.module]
            for name in names:
                root = name.split(".")[0]
                if root not in stdlib and root not in ("naivert", "__future__"):
                    roots.setdefault(root, set()).add(path)
    return {root: sorted(paths) for root, paths in sorted(roots.items())}


# --------------------------------------------------------------------------- build


def _load_oracle_dependencies():
    spec = importlib.util.spec_from_file_location(
        "_sglang_prefill_dependencies", ORACLE_DIR / "dependencies.py",
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return str(path.resolve())


def build(deps_dir: Path) -> tuple[dict[str, bytes], dict]:
    dependencies = _load_oracle_dependencies()
    oracle = dependencies.load_manifest()
    dependencies.check_dependencies(deps_dir, oracle)

    closure = fa4_closure(deps_dir / FA4_SOURCE)
    if closure != sorted(FA4_MODULES):
        raise VendorError(
            f"FA4 import closure changed: extra {sorted(set(closure) - set(FA4_MODULES))}, "
            f"missing {sorted(set(FA4_MODULES) - set(closure))}"
        )

    naive_ops = oracle["naive_ops"]
    patched_source = f"ops/{naive_ops['file']}"
    if patched_source not in {entry.source for entry in ENTRIES}:
        raise VendorError(f"no entry copies the oracle's patched file {patched_source}")

    files: dict[str, bytes] = {}
    records = []
    for entry in ENTRIES:
        record = {"path": entry.out, "mode": entry.mode, "license": entry.license}
        if entry.mode == "authored":
            data = entry.text.encode()
        else:
            raw = (deps_dir / entry.source).read_bytes()
            record["source"] = entry.source
            record["source_sha256"] = sha256_bytes(raw)
            copied_sha = record["source_sha256"]
            if entry.source == patched_source:
                if entry.mode != "extracted":
                    raise VendorError(f"{entry.out}: the patched file must be extracted")
                raw = _restore_upstream(raw, entry)
                copied_sha = sha256_bytes(raw)
                if copied_sha != naive_ops["original_sha256"]:
                    raise VendorError(
                        f"{entry.source}: reverting the oracle patch gives sha256 {copied_sha}, "
                        f"not the oracle's original_sha256 {naive_ops['original_sha256']}"
                    )
                record["upstream_restore"] = {
                    "old": ORACLE_PATCH_REVERSAL.old, "new": ORACLE_PATCH_REVERSAL.new,
                    "count": ORACLE_PATCH_REVERSAL.count, "why": ORACLE_PATCH_REVERSAL.why,
                    "upstream_sha256": copied_sha,
                }
            if entry.mode == "verbatim":
                if entry.substitutions:
                    raise VendorError(f"{entry.out}: verbatim entry with substitutions")
                data = raw
            elif entry.mode == "rewritten":
                data = _substitute(raw.decode(), entry).encode()
            elif entry.mode == "extracted":
                text, details = extract(raw.decode(), entry, copied_sha,
                                        upstream=entry.source == patched_source)
                data = _substitute(text, entry).encode()
                record["roots"] = list(entry.roots)
                record.update(details)
            else:
                raise VendorError(f"{entry.out}: unknown mode {entry.mode}")
        if entry.substitutions:
            record["substitutions"] = [
                {"old": s.old, "new": s.new, "count": s.count, "why": s.why}
                for s in entry.substitutions
            ]
        if entry.out.endswith(".py"):
            compile(data, entry.out, "exec", dont_inherit=True)
            banned = banned_references(data.decode(), entry.out)
            if banned:
                raise VendorError("banned references remain:\n  " + "\n  ".join(banned))
        record["sha256"] = sha256_bytes(data)
        if entry.out in files:
            raise VendorError(f"duplicate output {entry.out}")
        files[entry.out] = data
        records.append(record)

    manifest = {
        "schema_version": SCHEMA_VERSION,
        "generator": {
            "path": _relative(Path(__file__)),
            "sha256": sha256_bytes(Path(__file__).read_bytes()),
        },
        "reference": {
            "oracle_manifest": {
                "path": _relative(ORACLE_DIR / "manifest.json"),
                "sha256": sha256_bytes((ORACLE_DIR / "manifest.json").read_bytes()),
            },
            "sglang_revision": oracle["sglang"]["revision"],
            "naive_ops": {
                "distribution": naive_ops["distribution"],
                "version": oracle["distributions"][naive_ops["distribution"]],
                "patched_file": naive_ops["file"],
                "original_sha256": naive_ops["original_sha256"],
                "patched_sha256": naive_ops["patched_sha256"],
            },
        },
        "package": OUT_PACKAGE,
        "banned_import_roots": list(BANNED_ROOTS),
        "third_party_import_roots": third_party_roots(files),
        "files": sorted(records, key=lambda record: record["path"]),
    }
    files[MANIFEST_NAME] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return files, manifest


def _tree(root: Path) -> list[str]:
    if not root.exists():
        return []
    return sorted(
        path.relative_to(root).as_posix() for path in root.rglob("*")
        if path.is_file() and "__pycache__" not in path.relative_to(root).parts
    )


def check(out_dir: Path, files: dict[str, bytes]) -> list[str]:
    actual = set(_tree(out_dir))
    problems = []
    for path in sorted(actual | set(files)):
        if path not in actual:
            problems.append(f"missing: {path}")
        elif path not in files:
            problems.append(f"unexpected: {path}")
        elif (out_dir / path).read_bytes() != files[path]:
            problems.append(f"differs: {path}")
    return problems


def write(out_dir: Path, files: dict[str, bytes]) -> None:
    existing = _tree(out_dir)
    if existing:
        manifest_path = out_dir / MANIFEST_NAME
        if not manifest_path.is_file():
            raise VendorError(f"{out_dir} exists without {MANIFEST_NAME}; refusing to overwrite")
        generated = {record["path"] for record in json.loads(manifest_path.read_text())["files"]}
        foreign = [path for path in existing if path not in generated | {MANIFEST_NAME}]
        if foreign:
            raise VendorError(f"{out_dir} holds files the tool did not generate: {foreign}")
        for path in existing:
            if path not in files:
                (out_dir / path).unlink()
    for path, data in files.items():
        target = out_dir / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--deps-dir", type=Path, default=DEFAULT_DEPS_DIR)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--check", action="store_true",
                        help="fail unless --out-dir equals a fresh regeneration")
    args = parser.parse_args()
    try:
        files, manifest = build(args.deps_dir)
        if args.check:
            problems = check(args.out_dir, files)
            if problems:
                print("prefill_ext is stale:\n  " + "\n  ".join(problems), file=sys.stderr)
                return 1
            print(f"prefill_ext matches a fresh regeneration ({len(files)} files)")
            return 0
        write(args.out_dir, files)
    except VendorError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    for record in manifest["files"]:
        if record["mode"] == "extracted":
            kept = [item["name"] for item in record["kept"]]
            print(f"{record['path']}: kept {len(kept)}, dropped {len(record['dropped'])}: {kept}")
    print(f"wrote {len(files)} files to {_relative(args.out_dir)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
